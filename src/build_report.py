MONO_FONT = "Courier New"


def set_run_font(run, name=None, size=None, bold=None, italic=None):
    if name:
        run.font.name = name
        rpr = run._element.get_or_add_rPr()
        rFonts = rpr.find(qn('w:rFonts'))
        if rFonts is None:
            rFonts = OxmlElement('w:rFonts')
            rpr.append(rFonts)
        rFonts.set(qn('w:eastAsia'), name)
    if size:
        run.font.size = Pt(size)
    if bold is not None:
        run.bold = bold
    if italic is not None:
        run.italic = italic


def add_heading1(doc, text):
    p = doc.add_paragraph(text, style='Heading 1')
    return p


def add_heading2(doc, text):
    p = doc.add_paragraph(text, style='Heading 2')
    return p


def add_body(doc, text, bold=False, align=None):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.bold = bold
    if align:
        p.alignment = align
    return p


def add_code_block(doc, text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.first_line_indent = 0
    p.paragraph_format.left_indent = Cm(0.5)
    p.paragraph_format.line_spacing = 1.0
    run = p.add_run(text)
    set_run_font(run, name=MONO_FONT, size=10)
    return p


def add_figure(doc, path, caption, width_cm=14):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = 0
    run = p.add_run()
    run.add_picture(path, width=Cm(width_cm))

    cap = doc.add_paragraph()
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap.paragraph_format.first_line_indent = 0
    cap_run = cap.add_run(caption)
    cap_run.italic = True
    set_run_font(cap_run, size=11)
    return p


